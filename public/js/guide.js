const clean = (t) => String(t || '').toLowerCase().replace(/[*:]/g, '').replace(/\s*[—(].*$/s, '').replace(/\s+/g, ' ').trim();
/** Cari panduan untuk label pada bagian menu tertentu (bagian = segmen setelah #/admin/). */
export function guideFor(label, section = '') {
  const k = clean(label); if (!k) return '';
  return GUIDE[`${section}:${k}`] || GUIDE[k] || '';
}
